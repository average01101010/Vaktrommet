export const emptyUpgradeLevels = (): UpgradeLevels =>
  Object.fromEntries(UPGRADES.map((u) => [u.id, 0])) as UpgradeLevels

export const upgradeCost = (def: UpgradeDef, currentLevel: number): number =>
  Math.round((def.baseCost * Math.pow(def.costGrowth, currentLevel)) / 10) * 10
